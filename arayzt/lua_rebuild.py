"""Fail-closed recovery of legacy Project Zomboid PTBR tables.

Rebuilds ONLY simple one-line string assignments. All assignment-like lines must
be accounted for, and the resulting table must pass luaparser and value checks.
"""
from pathlib import Path
import re
from .lua_syntax import syntax_error

HEAD=re.compile(r'^\s*([A-Za-z_]\w*)\s*=\s*\{\s*(?:--.*)?$')
ASSIGN_START=re.compile(r'^\s*([A-Za-z_][\w.]*)\s*=\s*"')
CLOSE=re.compile(r'^\s*}\s*,?\s*(?:--.*)?$')
TAIL=re.compile(r'"\s*,?\s*(?:--.*)?$')
ANY_ASSIGN=re.compile(r'^\s*([A-Za-z_][\w.]*)\s*=')

def recover(text: str, changes: dict) -> tuple[str,dict]:
    from .core import lua_decode,lua_encode, read_lua
    header=None
    entries={}
    expected=0
    malformed=[]
    in_table=False
    for line_no,line in enumerate(text.splitlines(),1):
        v=line.strip()
        if not v or v.startswith('--'):
            continue
        m=HEAD.fullmatch(line)
        if m and header is None:
            header=m.group(1)
            in_table=True
            continue
        if CLOSE.fullmatch(line) and in_table:
            in_table=False
            continue
        if not in_table:
            # Reject executable Lua or nested tables that we cannot preserve.
            malformed.append({'line':line_no,'sample':v[:100],'reason':'outside_table'})
            continue
        m=ASSIGN_START.match(line)
        tail=TAIL.search(line)
        if not m or not tail or tail.start()<=m.end()-1:
            malformed.append({'line':line_no,'sample':v[:100],'reason':'unsupported_assignment'})
            continue
        key=m.group(1)
        content=line[m.end():tail.start()]
        # Strings generated by the translation system only require quoted
        # escape decoding; keep Lua control sequences unchanged otherwise.
        value=lua_decode(content)
        entries[key]=value
        expected+=1
    if header is None or in_table or malformed:
        return '',{'valid':False,'error':'unsupported_source_syntax','lines':malformed[:20]}
    recovered_count=len(entries)
    entries.update(changes)
    body=[f'{header} = {{']
    body.extend(f'    {key} = "{lua_encode(value)}",' for key,value in entries.items())
    body.append('}')
    result='\n'.join(body)+'\n'
    err=syntax_error(result)
    if err:
        return '',{'valid':False,'error':err}
    # Parsed key count must account for every original unique key + change.
    from tempfile import TemporaryDirectory
    with TemporaryDirectory() as td:
        target=Path(td)/'rebuilt.txt'
        target.write_text(result,encoding='utf-8')
        verified=read_lua(target)
    if verified != entries:
        return '',{'valid':False,'error':'round_trip_value_mismatch'}
    return result,{'valid':True,'source_entries':expected,'source_unique':recovered_count,
                   'total_keys':len(entries),'replaced_keys':len(changes),
                   'duplicate_source_keys':expected-recovered_count}
